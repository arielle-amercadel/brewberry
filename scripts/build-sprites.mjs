// Converts the text grids in art/sprites/ into PNGs in src/assets/sprites/,
// writes a typed manifest for React, and draws public/favicon.svg from the logo.
// Each character in a grid is one pixel; art/palette.json maps characters to
// colours. Uses only Node built-ins. Run with: npm run sprites
//
// Sprites named panel-* or tile-* are only used from CSS, so they stay out of
// the manifest and out of the JavaScript bundle.
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { basename, dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { crc32, deflateSync } from "node:zlib";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const gridDir = join(root, "art", "sprites");
const outDir = join(root, "src", "assets", "sprites");
const gridStep = 4;
const sheetGap = 4;
const sheetWidth = 256;

const rawPalette = Object.entries(
  JSON.parse(readFileSync(join(root, "art", "palette.json"), "utf8")),
);
const palette = new Map(
  rawPalette.map(([char, { hex }]) => [char, hex ? hexToRgba(hex) : [0, 0, 0, 0]]),
);
const hexByChar = new Map(rawPalette.map(([char, { hex }]) => [char, hex]));

function hexToRgba(hex) {
  const n = Number.parseInt(hex.slice(1), 16);
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255, 255];
}

function readGrid(path) {
  const name = basename(path);
  const rows = readFileSync(path, "utf8").trimEnd().split(/\r?\n/);
  const width = rows[0].length;
  if (width % gridStep !== 0 || rows.length % gridStep !== 0) {
    throw new Error(
      `${name}: ${width}x${rows.length}; both sides must be multiples of ${gridStep}`,
    );
  }
  rows.forEach((row, y) => {
    if (row.length !== width) {
      throw new Error(`${name} row ${y}: ${row.length} columns; expected ${width}`);
    }
    for (const char of row) {
      if (!palette.has(char)) {
        throw new Error(`${name} row ${y}: "${char}" is not in the palette`);
      }
    }
  });
  return rows;
}

function pngChunk(type, data) {
  const typed = Buffer.concat([Buffer.from(type, "latin1"), data]);
  const chunk = Buffer.alloc(typed.length + 8);
  chunk.writeUInt32BE(data.length, 0);
  typed.copy(chunk, 4);
  chunk.writeUInt32BE(crc32(typed), typed.length + 4);
  return chunk;
}

// pixels: array of rows, each row an array of [r, g, b, a].
function encodePng(pixels) {
  const height = pixels.length;
  const width = pixels[0].length;
  const header = Buffer.alloc(13);
  header.writeUInt32BE(width, 0);
  header.writeUInt32BE(height, 4);
  header[8] = 8; // bits per channel
  header[9] = 6; // RGBA
  const raw = Buffer.alloc((width * 4 + 1) * height);
  pixels.forEach((row, y) => {
    row.forEach((rgba, x) => {
      raw.set(rgba, y * (width * 4 + 1) + 1 + x * 4);
    });
  });
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    pngChunk("IHDR", header),
    pngChunk("IDAT", deflateSync(raw, { level: 9 })),
    pngChunk("IEND", Buffer.alloc(0)),
  ]);
}

// Packs sprites into rows, left to right, each row sharing a baseline.
function buildSheet(sprites) {
  const shelves = [];
  let shelf = [];
  let used = sheetGap;
  for (const sprite of sprites) {
    const width = sprite.pixels[0].length;
    if (used + width + sheetGap > sheetWidth && shelf.length > 0) {
      shelves.push(shelf);
      shelf = [];
      used = sheetGap;
    }
    shelf.push(sprite);
    used += width + sheetGap;
  }
  shelves.push(shelf);

  const heights = shelves.map((row) =>
    Math.max(...row.map((sprite) => sprite.pixels.length)),
  );
  const height = heights.reduce((sum, h) => sum + h + sheetGap, sheetGap);
  const sheet = Array.from({ length: height }, () =>
    Array.from({ length: sheetWidth }, () => [0, 0, 0, 0]),
  );
  let bottom = sheetGap;
  shelves.forEach((row, i) => {
    bottom += heights[i];
    let left = sheetGap;
    for (const { pixels } of row) {
      const top = bottom - pixels.length;
      pixels.forEach((line, y) => {
        line.forEach((rgba, x) => {
          sheet[top + y][left + x] = rgba;
        });
      });
      left += pixels[0].length + sheetGap;
    }
    bottom += sheetGap;
  });
  return sheet;
}

function buildManifest(sprites) {
  const used = sprites.filter(({ name }) => !/^(panel|tile)-/.test(name));
  const id = (name) => name.replace(/-(\w)/g, (_, c) => c.toUpperCase());
  const imports = used.map(
    ({ name }) => `import ${id(name)} from "./${name}.png";`,
  );
  const entries = used.map(
    ({ name, pixels }) =>
      `  "${name}": { src: ${id(name)}, width: ${pixels[0].length}, height: ${pixels.length} },`,
  );
  return [
    "// Generated by scripts/build-sprites.mjs. Do not edit by hand.",
    ...imports,
    "",
    "export const sprites = {",
    ...entries,
    "} as const;",
    "",
    "export type SpriteName = keyof typeof sprites;",
    "",
  ].join("\n");
}

function buildFaviconSvg(rows) {
  const rects = [];
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; ) {
      let end = x + 1;
      while (end < row.length && row[end] === row[x]) end += 1;
      const hex = hexByChar.get(row[x]);
      if (hex) {
        rects.push(
          `<rect x="${x}" y="${y}" width="${end - x}" height="1" fill="${hex}"/>`,
        );
      }
      x = end;
    }
  });
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${rows[0].length} ${rows.length}" shape-rendering="crispEdges">${rects.join("")}</svg>\n`;
}

const sprites = readdirSync(gridDir)
  .filter((file) => file.endsWith(".txt"))
  .sort()
  .map((file) => {
    const rows = readGrid(join(gridDir, file));
    return {
      name: basename(file, ".txt"),
      rows,
      pixels: rows.map((row) => [...row].map((char) => palette.get(char))),
    };
  });

mkdirSync(outDir, { recursive: true });
for (const { name, pixels } of sprites) {
  writeFileSync(join(outDir, `${name}.png`), encodePng(pixels));
}
writeFileSync(join(outDir, "_sheet.png"), encodePng(buildSheet(sprites)));
writeFileSync(join(outDir, "manifest.ts"), buildManifest(sprites));
const logo = sprites.find(({ name }) => name === "logo");
writeFileSync(join(root, "public", "favicon.svg"), buildFaviconSvg(logo.rows));
console.log(`Built ${sprites.length} sprites in src/assets/sprites`);
